import type { ReactNode } from "react";
import type { QueryClient } from "@tanstack/react-query";

// Описание «галереи состояний»: страницы разработчика, где видны все состояния
// интерфейса без сервера. Каждая фича отдаёт свои записи, страница только
// раскладывает их по разделам. Типы лежат здесь, потому что фичи не знают о
// страницах и друг о друге.

export type GalleryFrame =
  /** Содержимое окна: рамка и фон окна, ширина по записи. */
  | "window"
  /** Страница с собственными отступами (мастер клонирования): рамка без своих полей. */
  | "page"
  /** Само по себе, на фоне страницы (кнопка, панель, карточка). */
  | "plain"
  /** На весь экран: страница с собственной высотой (экран конфликтов). */
  | "screen";

export type GalleryEntry = {
  id: string;
  /** Короткое название состояния для разработчика и владельца продукта. */
  title: string;
  /** На что смотреть: одно предложение. */
  note?: string;
  frame?: GalleryFrame;
  /** Ширина рамки, px. */
  width?: number;
  render: () => ReactNode;
  /** Заполнить кэш запросов записи: так шаг видит данные без сервера. */
  seed?: (client: QueryClient) => void;
  /**
   * Запись живая: работает на демо-API в памяти вкладки. Показывается по кнопке
   * «Открыть», потому что одновременно может быть настроен только один сценарий.
   * Значение: идентификатор демо-сценария.
   */
  scenario?: string;
};

export type GalleryGroup = {
  id: string;
  title: string;
  description?: string;
  entries: GalleryEntry[];
};

export type GallerySection = {
  id: string;
  title: string;
  groups: GalleryGroup[];
};

