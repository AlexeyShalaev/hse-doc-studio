"""Версия содержимого файла — чтобы правка снаружи не пропадала молча.

Проект живёт обычной папкой на диске, и это осознанно: тот же `.tex` пользователь
открывает и в Студии, и в VS Code. Пока `GET` отдавал содержимое без всякой
пометки о версии, а `PUT` писал безусловно, получалась классическая «потеря
обновления»: Студия затирала правку, сделанную снаружи, и никто об этом не узнавал.

Версия — хеш СОДЕРЖИМОГО, а не время правки: `mtime` у бинд-маунтов Docker
округляется и меняется от простого `touch`, а хеш отвечает ровно на тот вопрос,
который задан, — «это тот же текст, который я показал пользователю?».

Формат совпадает с HTTP-ETag, поэтому по проводу едет штатными `ETag`/`If-Match`,
а не самодельным заголовком.
"""

from __future__ import annotations

import hashlib

# Половины sha256 с запасом хватает: коллизия здесь означала бы «два разных текста
# сочтены одинаковыми», а не брешь в безопасности.
_DIGEST_CHARS = 32


def file_etag(content: bytes) -> str:
    """ETag содержимого — в кавычках, как требует HTTP."""
    return f'"{hashlib.sha256(content).hexdigest()[:_DIGEST_CHARS]}"'


def etag_matches(expected: str | None, content: bytes) -> bool:
    """Совпадает ли версия, на которую опирался клиент, с тем, что лежит сейчас.

    `None` (заголовка нет) — согласие на безусловную запись: так пишут агент и
    внутренние операции, которые не редактируют пользовательский буфер.
    `*` — тоже безусловно, по семантике HTTP.
    """
    if expected is None:
        return True
    candidates = {tag.strip() for tag in expected.split(",")}
    if "*" in candidates:
        return True
    actual = file_etag(content)
    # Слабые валидаторы (W/"…") нам не нужны, но принять их вежливее, чем упасть.
    return any(tag.removeprefix("W/") == actual for tag in candidates)
