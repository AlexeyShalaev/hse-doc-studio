"""Маршрут подписания «Отправить на подписание» (docs/design/signing-route.md).

- `entities`: маршрут, участники, согласия, события, статусы и ошибки;
- `engine`: факты о документах и чистый расчёт `evaluate()`: фаза, L, ход участников, остановка, эффекты;
- `effects`: что сценарии должны сделать по итогам расчёта (придержать, открыть, зафиксировать, уведомить);
- `transitions`: переходы маршрута (отправить, согласовать, вернуть, отменить, применить расчёт);
- `repositories`: порт хранилища маршрутов и его ошибки (реализация на Postgres в `infra/db`, только сервер);
- `drafting`: черновик автора: люди по персонам, пары «документ, слот» по участникам, правка людей;
- `readiness`: помехи отправки и отказы `route_blocked`, `doc_changed`;
- `notices`: уведомления маршрута: адресаты, ключ повтора, письма, пометка запросов и порт доставки;
- `reminders`: напоминания: интервал ручного «Напомнить», правила автонапоминаний, отметка и событие;
- `ports`: доставка уведомлений (`ISigningNotifier`), люди проекта (`IRoutePeople`), факты документов маршрута и
  подписи для экранов (точка, проект), счётчик задач «На подпись».

Здесь только чистые значения, функции и порты: без БД, HTTP и файлов.
"""
