"""Цвет человека в совместной работе: один и тот же у курсора в документе и у аватара в шапке проекта."""

from __future__ import annotations

# Насыщенные цвета, читаются на светлой и тёмной теме; подсветка выделения это тот же цвет с прозрачностью.
PALETTE = ("#d6336c", "#1c7ed6", "#2f9e44", "#e8590c", "#7048e8", "#0c8599", "#c2255c", "#5c940d")


def person_color(key: str) -> str:
    """Цвет по ключу человека (id пользователя или гостевой сессии): не меняется от имени и от проекта."""
    return PALETTE[sum(key.encode("utf-8")) % len(PALETTE)]
